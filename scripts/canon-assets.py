"""Extracts the icons and bitmaps of the original Canon driver UI (CAP1UIK.DLL) for our UI DLL.

The artwork belongs to Canon and is not part of this repository: it is taken at build time from
the user's copy of the original driver. Without it, plain placeholders with the same resource
IDs are generated so that the build still works.

usage: canon-assets.py <Canon driver folder or ""> <output folder>
Writes <output>/assets.rc (+ .ico/.bmp files) to be included by src/driver/ui/ui.rc.
"""
import os
import struct
import sys

RT_BITMAP, RT_ICON, RT_GROUP_ICON = 2, 3, 14

# Resource IDs used by our UI (same numbers as in CAP1UIK.DLL).
ICONS = list(range(102, 169))
BITMAPS = list(range(200, 214))


class PE:
    def __init__(self, path):
        d = self.d = open(path, 'rb').read()
        pe = struct.unpack_from('<I', d, 0x3c)[0]
        nsec = struct.unpack_from('<H', d, pe + 6)[0]
        optsz = struct.unpack_from('<H', d, pe + 20)[0]
        opt = pe + 24
        magic = struct.unpack_from('<H', d, opt)[0]
        dd = opt + (96 if magic == 0x10b else 112)
        self.res_rva = struct.unpack_from('<I', d, dd + 16)[0]
        self.secs = []
        for i in range(nsec):
            _, vsz, va, rsz, raw = struct.unpack_from('<8sIIII', d, opt + optsz + 40 * i)
            self.secs.append((va, max(vsz, rsz), raw))
        self.res = {}
        base = self.off(self.res_rva)

        def walk(o, path):
            nn, ni = struct.unpack_from('<HH', d, o + 12)
            for i in range(nn + ni):
                nv, ov = struct.unpack_from('<II', d, o + 16 + 8 * i)
                key = path + [nv if not nv & 0x80000000 else None]
                if ov & 0x80000000:
                    walk(base + (ov & 0x7fffffff), key)
                else:
                    rva, sz = struct.unpack_from('<II', d, base + ov)
                    t, n = key[0], key[1]
                    if t is not None and n is not None:
                        self.res.setdefault((t, n), self.d[self.off(rva):self.off(rva) + sz])
        walk(base, [])

    def off(self, rva):
        for va, sz, raw in self.secs:
            if va <= rva < va + sz:
                return rva - va + raw
        raise ValueError(hex(rva))


def make_ico(pe, gid):
    g = pe.res[(RT_GROUP_ICON, gid)]
    n = struct.unpack_from('<H', g, 4)[0]
    entries, images = [], []
    for i in range(n):
        w, h, c, r, planes, bc, sz, iid = struct.unpack_from('<BBBBHHIH', g, 6 + 14 * i)
        img = pe.res[(RT_ICON, iid)]
        entries.append((w, h, c, r, planes, bc, len(img)))
        images.append(img)
    out = struct.pack('<HHH', 0, 1, n)
    offset = 6 + 16 * n
    for (w, h, c, r, planes, bc, sz) in entries:
        out += struct.pack('<BBBBHHII', w, h, c, r, planes, bc, sz, offset)
        offset += sz
    return out + b''.join(images)


def make_bmp(dib):
    hs, _, _, _, bpp, _, _, _, _, clr, _ = struct.unpack_from('<IiiHHIIiiII', dib)
    ncol = clr or (1 << bpp if bpp <= 8 else 0)
    bits = 14 + hs + 4 * ncol
    return struct.pack('<HIHHI', 0x4D42, 14 + len(dib), 0, 0, bits) + dib


def placeholder_ico():
    # 32x32, 4bpp, fully transparent
    hdr = struct.pack('<IiiHHIIiiII', 40, 32, 64, 1, 4, 0, 0, 0, 0, 16, 0)
    pal = b'\x00\x00\x00\x00' * 16
    xor = b'\x00' * (16 * 32)
    andm = b'\xff' * (4 * 32)
    img = hdr + pal + xor + andm
    return struct.pack('<HHH', 0, 1, 1) + struct.pack('<BBBBHHII', 32, 32, 16, 0, 1, 4, len(img), 22) + img


def placeholder_bmp():
    dib = struct.pack('<IiiHHIIiiII', 40, 8, 8, 1, 24, 0, 0, 0, 0, 0, 0) + b'\xff' * (24 * 8)
    return make_bmp(dib)


def main():
    src, out = sys.argv[1], sys.argv[2]
    os.makedirs(out, exist_ok=True)
    dll = os.path.join(src, 'CAP1UIK.DLL') if src else ''
    pe = PE(dll) if dll and os.path.isfile(dll) else None
    lines = ['// generated by scripts/canon-assets.py - do not edit\n']
    lines.append('#define LBP_CANON_ASSETS %d\n' % (1 if pe else 0))
    for i in ICONS:
        data = make_ico(pe, i) if pe and (RT_GROUP_ICON, i) in pe.res else placeholder_ico()
        name = 'icon_%d.ico' % i
        open(os.path.join(out, name), 'wb').write(data)
        lines.append('%d ICON "%s"\n' % (i, name))
    for i in BITMAPS:
        data = make_bmp(pe.res[(RT_BITMAP, i)]) if pe and (RT_BITMAP, i) in pe.res else placeholder_bmp()
        name = 'bmp_%d.bmp' % i
        open(os.path.join(out, name), 'wb').write(data)
        lines.append('%d BITMAP "%s"\n' % (i, name))
    open(os.path.join(out, 'assets.rc'), 'w', encoding='ascii').writelines(lines)
    print('assets: %s (%s)' % (out, 'from ' + dll if pe else 'placeholders'))


if __name__ == '__main__':
    main()
